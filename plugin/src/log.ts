import { appendFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { stateDir } from "./paths.ts";

export type Level = "debug" | "info" | "warn" | "error";

const MAX_MEMORY = 300;
const memory: string[] = [];

/** Values that must never appear in a log line, no matter who logs them. */
const secrets = new Set<string>();

export function registerSecret(value: string | undefined | null): void {
  if (value && value.length >= 8) secrets.add(value);
}

export function redact(text: string): string {
  let out = text;
  for (const s of secrets) out = out.split(s).join("<redacted>");
  // gateway keys and bearer tokens, even when they were not registered
  out = out.replace(/sk-[A-Za-z0-9._-]{12,}/g, "<redacted-key>");
  out = out.replace(/(Bearer\s+)[A-Za-z0-9._-]{12,}/gi, "$1<redacted>");
  out = out.replace(/(network_secret\s*=\s*")[^"]+(")/gi, "$1<redacted>$2");
  out = out.replace(/(local-private-key[= ]+)[A-Za-z0-9+/=_-]{16,}/gi, "$1<redacted>");
  return out;
}

function logFile(): string {
  return join(stateDir(), "plugin.log");
}

let ready = false;

function ensureDir(): void {
  if (ready) return;
  mkdirSync(stateDir(), { recursive: true, mode: 0o700 });
  ready = true;
}

export function log(level: Level, message: string): void {
  const line = `${new Date().toISOString()} ${level.toUpperCase()} ${redact(message)}`;
  memory.push(line);
  if (memory.length > MAX_MEMORY) memory.splice(0, memory.length - MAX_MEMORY);
  try {
    ensureDir();
    appendFileSync(logFile(), line + "\n", { mode: 0o600 });
  } catch {
    /* the log is best effort */
  }
  if (level === "error") console.error(`[oh-my-aihub] ${line}`);
  else if (level === "warn") console.error(`[oh-my-aihub] ${line}`);
  else console.error(`[oh-my-aihub] ${line}`);
}

export const logger = {
  debug: (m: string) => log("debug", m),
  info: (m: string) => log("info", m),
  warn: (m: string) => log("warn", m),
  error: (m: string) => log("error", m),
};

export function recentLogs(n = 50): string[] {
  return memory.slice(-n).map(redact);
}

export function readLogFile(n = 200): string[] {
  try {
    return readFileSync(logFile(), "utf8").trim().split("\n").slice(-n).map(redact);
  } catch {
    return [];
  }
}

// --- status snapshot for the plugin page -------------------------------------
//
// A plugin page is served with `connect-src 'none'` (Magpie
// internal/gui/pluginpage.go), so it cannot fetch the host's HTTP API — not even
// on 127.0.0.1. Scripts from the page's own folder are allowed, so the host
// writes a plain `status.js` there and the page reloads to read it.

export function writePageStatus(snapshot: unknown): void {
  try {
    const file = join(import.meta.dir, "..", "page", "status.js");
    const body = `// generated by the plugin host; do not edit\nwindow.__OH_MY_AIHUB_STATUS__ = ${JSON.stringify(snapshot)};\n`;
    writeFileSync(file, body, { mode: 0o644 });
  } catch (e) {
    log("warn", `cannot write page/status.js: ${String(e)}`);
  }
}
